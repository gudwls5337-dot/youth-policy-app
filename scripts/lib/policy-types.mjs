/** 정책명에서 유형 서명을 뽑는다. 해당 없으면 "" — 추정하지 않는다. */
export function typeSig(name) {
  const s = String(name || "");
  const hit = CORE_TYPES.filter(([, re]) => re.test(s)).map(([k]) => k);
  return hit.length ? hit.sort().join("+") : "";
}

/** 사람이 읽을 이름 */
export const typeLabel = sig => sig.split("+").join(" · ");
